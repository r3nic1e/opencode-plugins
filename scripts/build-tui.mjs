#!/usr/bin/env node
// Compiles packages/<name>/src/tui.tsx to packages/<name>/dist/tui.js.
//
// OpenCode's TUI compiles plugin JSX with the OpenTUI Solid transform, but that transform skips
// every file under node_modules, where npm installs plugins. Bun then falls back to its generic
// JSX runtime, which evaluates props once, so reactive JSX such as <Show when={...}> never updates.
// A published TUI entry must therefore be Solid-compiled JavaScript.
//
// Usage: build-tui.mjs [--check] [package-dir...]  (default: every package with src/tui.tsx)
import { transformAsync } from "@babel/core"
import ts from "@babel/preset-typescript"
import solid from "babel-preset-solid"
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const HEADER = "// Generated by scripts/build-tui.mjs from src/tui.tsx. Do not edit.\n"

// dist/tui.js imports its sibling modules from src/, which OpenCode loads as TypeScript.
function srcImports() {
  const rewrite = (source) => {
    if (source?.value.startsWith("./")) source.value = `../src/${source.value.slice(2)}`
  }
  return {
    visitor: {
      ImportDeclaration: (p) => rewrite(p.node.source),
      ExportNamedDeclaration: (p) => rewrite(p.node.source),
      ExportAllDeclaration: (p) => rewrite(p.node.source),
    },
  }
}

// Keep in sync with @opentui/solid/scripts/solid-transform.js, which compiles local plugins.
export async function compile(code, filename) {
  const result = await transformAsync(code, {
    filename,
    configFile: false,
    babelrc: false,
    plugins: [srcImports],
    presets: [[solid, { moduleName: "@opentui/solid", generate: "universal" }], [ts]],
  })
  return HEADER + result.code + "\n"
}

export function tuiPackages() {
  return readdirSync(path.join(root, "packages"))
    .map((name) => path.join(root, "packages", name))
    .filter((dir) => existsSync(path.join(dir, "src", "tui.tsx")))
}

export async function build(dir) {
  const source = path.join(dir, "src", "tui.tsx")
  return { out: path.join(dir, "dist", "tui.js"), code: await compile(readFileSync(source, "utf8"), source) }
}

async function main(args) {
  const check = args.includes("--check")
  const dirs = args.filter((arg) => arg !== "--check").map((arg) => path.resolve(arg))
  let stale = 0
  for (const dir of dirs.length ? dirs : tuiPackages()) {
    const { out, code } = await build(dir)
    if (check) {
      if (!existsSync(out) || readFileSync(out, "utf8") !== code) {
        console.error(`stale: ${path.relative(root, out)}`)
        stale++
      }
      continue
    }
    mkdirSync(path.dirname(out), { recursive: true })
    writeFileSync(out, code)
    console.log(`built ${path.relative(root, out)}`)
  }
  if (stale) {
    console.error("Run `npm run build` and commit the result.")
    process.exit(1)
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main(process.argv.slice(2))
